CREATE SCHEMA IF NOT EXISTS tracker;
CREATE TABLE IF NOT EXISTS tracker.config(key text PRIMARY KEY,value text NOT NULL);
CREATE TABLE IF NOT EXISTS tracker.users(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,email text UNIQUE NOT NULL,password text NOT NULL,
  recovery text,theme text NOT NULL DEFAULT 'light' CHECK(theme IN ('light','dark')),threshold bigint NOT NULL DEFAULT 0 CHECK(threshold>=0)
);
ALTER TABLE tracker.users ADD COLUMN IF NOT EXISTS username text UNIQUE;
ALTER TABLE tracker.users ADD COLUMN IF NOT EXISTS admin boolean NOT NULL DEFAULT false;
CREATE TABLE IF NOT EXISTS tracker.sessions(id text PRIMARY KEY,owner integer NOT NULL REFERENCES tracker.users(id),expires bigint NOT NULL);
CREATE TABLE IF NOT EXISTS tracker.resets(code text PRIMARY KEY,owner integer NOT NULL REFERENCES tracker.users(id),expires bigint NOT NULL);
CREATE TABLE IF NOT EXISTS tracker.attempts(key text PRIMARY KEY,count integer NOT NULL,until_ms bigint NOT NULL);
CREATE TABLE IF NOT EXISTS tracker.entries(
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,owner integer NOT NULL REFERENCES tracker.users(id),
 type text NOT NULL CHECK(type IN ('delivery','payment','price')),date date NOT NULL,cents bigint NOT NULL CHECK(cents>0),
 qty integer NOT NULL DEFAULT 1 CHECK(qty>0),method text NOT NULL DEFAULT '',notes text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS entries_owner ON tracker.entries(owner,date,id);
CREATE TABLE IF NOT EXISTS tracker.alerts(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,owner integer NOT NULL REFERENCES tracker.users(id),date date NOT NULL,cents bigint NOT NULL,seen integer NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS tracker.subscriptions(endpoint text PRIMARY KEY,owner integer NOT NULL REFERENCES tracker.users(id),session text NOT NULL REFERENCES tracker.sessions(id) ON DELETE CASCADE,subscription text NOT NULL);

-- Keep receipts after an entry is deleted: a delayed retry must not recreate it.
CREATE TABLE IF NOT EXISTS tracker.entry_receipts(
 owner integer NOT NULL REFERENCES tracker.users(id) ON DELETE CASCADE,
 key uuid NOT NULL,entry_id integer NOT NULL,fingerprint text NOT NULL,PRIMARY KEY(owner,key)
);
DO $grants$
DECLARE role_name text;
BEGIN
 FOR role_name IN SELECT grantee FROM information_schema.table_privileges
  WHERE table_schema='tracker' AND table_name='entries' AND privilege_type='INSERT' AND grantee<>current_user
 LOOP
  EXECUTE format('GRANT SELECT,INSERT ON tracker.entry_receipts TO %I',role_name);
 END LOOP;
END $grants$;
